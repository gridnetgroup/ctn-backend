// ---------------------------------------------------------------------------
// Minimal JSON-file "database" so this backend runs with zero external setup.
//
// This is fine for local development and demos. Before going live, swap this
// file for a real database client (Postgres via Supabase/Neon/RDS is the
// natural fit) — every other file in this project only calls the functions
// exported here, so that's the only file you'd need to rewrite.
// ---------------------------------------------------------------------------
const path = require('path');
const low = require('lowdb');
const FileSync = require('lowdb/adapters/FileSync');

const adapter = new FileSync(path.join(__dirname, '..', 'submissions.json'));
const db = low(adapter);

db.defaults({ submissions: [] }).write();

/**
 * Create a submission in "pending_payment" status — this happens the moment
 * someone clicks "Confirm & Continue to Payment" on the review step, BEFORE
 * they've actually paid. We need a row to exist so the Whop Checkout
 * Session can reference it by id in its metadata.
 */
function createPendingSubmission(data) {
  const submission = {
    id: data.id, // e.g. "CTN-482910", generated by the route handler
    status: 'pending_payment', // pending_payment -> pending_review -> approved -> published (or rejected)
    company: data.company,
    contactName: data.contactName,
    email: data.email,
    website: data.website || '',
    headline: data.headline,
    body: data.body,
    imageUrl: data.imageUrl || null,
    keywords: data.keywords || [],
    mediaContact: data.mediaContact || '',
    publishDate: data.publishDate || 'asap',
    gatewayOrderToken: null,
    gatewayTransactionId: null,
    createdAt: new Date().toISOString(),
    paidAt: null,
    reviewedAt: null,
    publishedAt: null,
  };
  db.get('submissions').push(submission).write();
  return submission;
}

function attachGatewayOrderToken(id, gatewayOrderToken) {
  db.get('submissions').find({ id }).assign({ gatewayOrderToken }).write();
}

function getSubmission(id) {
  return db.get('submissions').find({ id }).value();
}

function getSubmissionByGatewayOrderToken(gatewayOrderToken) {
  return db.get('submissions').find({ gatewayOrderToken }).value();
}

/**
 * Called only after independently confirming payment with the gateway
 * (see src/payment.js fetchOrderStatus) — never from a client request.
 */
function markPaid(id, gatewayTransactionId) {
  db.get('submissions')
    .find({ id })
    .assign({
      status: 'pending_review',
      gatewayTransactionId,
      paidAt: new Date().toISOString(),
    })
    .write();
  return getSubmission(id);
}

function listSubmissions(status) {
  const all = db.get('submissions').value();
  return status ? all.filter(s => s.status === status) : all;
}

function updateStatus(id, status) {
  const patch = { status };
  if (status === 'approved' || status === 'rejected') patch.reviewedAt = new Date().toISOString();
  if (status === 'published') patch.publishedAt = new Date().toISOString();
  db.get('submissions').find({ id }).assign(patch).write();
  return getSubmission(id);
}

module.exports = {
  createPendingSubmission,
  attachGatewayOrderToken,
  getSubmission,
  getSubmissionByGatewayOrderToken,
  markPaid,
  listSubmissions,
  updateStatus,
};
